package jp.linkserver.nittcsc.sktjf

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class SktjfV3CandidateJsonTest {
    private fun candidate(): JSONObject {
        val root = JSONObject(requireNotNull(javaClass.getResourceAsStream("/sktjf/synthetic-v1.json")).bufferedReader().use { it.readText() })
        root.put("schemaVersion", 3)
        val lessons = root.getJSONArray("lessons")
        val first = lessons.getJSONObject(0)
        lessons.put(JSONObject(first.toString()).put("id", "alternative").put("subject", "選択授業"))
        root.put("selectionGroups", JSONArray().put(JSONObject().put("id", "group")
            .put("dayOfWeek", first.getInt("dayOfWeek")).put("period", first.getInt("period"))
            .put("lessonIds", JSONArray().put(first.getString("id")).put("alternative"))
            .put("sources", JSONArray(first.getJSONArray("sources").toString()))))
        return root
    }
    @Test fun explicitGroupIsRetainedAndOlderParsersRejectNewFormat() {
        val json = candidate()
        val result = SktjfV3CandidateJson.parse(json.toString().toByteArray())
        assertEquals(listOf("stable-id", "alternative"), result.selectionGroups.single().lessonIds)
        assertTrue(runCatching { SktjfV2CandidateJson.parse(json.toString().toByteArray()) }.isFailure)
    }
    @Test fun parsesSelectionGroupProducedByTheWebExporter() {
        // Generated by SKTJF's buildDistributionV3 from its synthetic project fixture.
        val bytes = requireNotNull(javaClass.getResourceAsStream("/sktjf/synthetic-v3-web.json")).use { it.readBytes() }
        val candidate = SktjfV3CandidateJson.parse(bytes)
        assertEquals("1-1", candidate.timetable.document.classId)
        assertEquals(listOf("stable-id", "alternative"), candidate.selectionGroups.single().lessonIds)
        assertEquals(setOf("数学", "選択授業"), candidate.timetable.document.lessons.map { it.subject }.toSet())
        assertEquals(setOf(SktjfCycle.A), candidate.timetable.document.lessons.map { it.cycle }.toSet())
    }
    @Test fun verifiesWebReleaseManifestAndExactAssetBytes() {
        fun resource(name: String) = requireNotNull(javaClass.getResourceAsStream("/sktjf/$name")).use { it.readBytes() }
        val manifest = SktjfV3DistributionJson.manifest(resource("synthetic-v3-web-manifest.json"), "example/SKTJF")
        val asset = manifest.common.assets.single()
        val bytes = resource("synthetic-v3-web.json")
        val result = SktjfV3DistributionJson.verifiedDocument(bytes, manifest, asset) as SktjfV3Asset.V3
        assertEquals(listOf("stable-id", "alternative"), result.candidate.selectionGroups.single().lessonIds)
        assertTrue(runCatching { SktjfV3DistributionJson.verifiedDocument(bytes + byteArrayOf(32), manifest, asset) }.isFailure)
    }
    @Test fun wrongPeriodAndDuplicateMembershipAreRejected() {
        val wrong = candidate(); wrong.getJSONArray("selectionGroups").getJSONObject(0).put("period", 2)
        assertTrue(runCatching { SktjfV3CandidateJson.parse(wrong.toString().toByteArray()) }.isFailure)
        val duplicate = candidate(); val groups = duplicate.getJSONArray("selectionGroups")
        groups.put(JSONObject(groups.getJSONObject(0).toString()).put("id", "another"))
        assertTrue(runCatching { SktjfV3CandidateJson.parse(duplicate.toString().toByteArray()) }.isFailure)
    }
    @Test fun explicitAlternativesCanShareAnActiveWeek() {
        val json = candidate()
        val lessons = json.getJSONArray("lessons")
        for (index in 0 until lessons.length()) lessons.getJSONObject(index).put("activeWeekRange",
            JSONObject().put("start", 1).put("end", JSONObject.NULL).put("notation", "1週〜"))
        json.put("weekCalendar", JSONArray().put(JSONObject().put("date", "2026-04-06").put("week", 1)
            .put("sources", JSONArray().put(JSONObject().put("sourceId", "src").put("page", 1)))))
        assertEquals(2, SktjfV3CandidateJson.parse(json.toString().toByteArray()).timetable.ranges.size)
        val noGroup = JSONObject(json.toString()).put("selectionGroups", JSONArray())
        assertTrue(runCatching { SktjfV3CandidateJson.parse(noGroup.toString().toByteArray()) }.isFailure)
    }
}
